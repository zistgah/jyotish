"""Bundle config/*.json into config/bundle.js so the page works from file:// and offline.

The JSON files are the source; bundle.js is generated and checked by the test suite
(it must equal a fresh build). Usage: python3 tools/build_config.py [--check]
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
CFG = os.path.join(HERE, "..", "config")
def build():
    out = {}
    for f in sorted(os.listdir(CFG)):
        if f.endswith(".json"):
            key = f[:-5].replace(".config", "")
            out[key] = json.load(open(os.path.join(CFG, f), encoding="utf-8"))
    body = json.dumps(out, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    return ("/* GENERATED by tools/build_config.py from config/*.json. Edit the JSON, then rebuild. */\n"
            "(function(r){r.JyotishConfig=" + body + ";})(typeof self!=='undefined'?self:this);\n")
text = build()
path = os.path.join(CFG, "bundle.js")
if "--check" in sys.argv:
    same = os.path.exists(path) and open(path, encoding="utf-8").read() == text
    print("bundle current" if same else "bundle STALE: run python3 tools/build_config.py")
    sys.exit(0 if same else 1)
open(path, "w", encoding="utf-8").write(text)
print("wrote config/bundle.js", len(text.encode("utf-8")), "bytes")
