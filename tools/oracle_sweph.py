"""Write tests/vectors/oracle.json: reference numbers from an INDEPENDENT ephemeris.

Optional and external. Needs pyswisseph (installed separately, never vendored); it runs
in Moshier mode, so no ephemeris files are needed. Only its outputs, which are numbers,
enter the tree, with the tool's version recorded, so the test suite runs without it.
Times are fed as TT (JDE) computed by the engine's own Delta-T, which isolates the
ephemeris from the Delta-T model when the two are compared.
"""
import json, subprocess, sys
import swisseph as swe
FL = swe.FLG_MOSEPH | swe.FLG_SPEED
BODIES = {"Sun": swe.SUN, "Moon": swe.MOON, "Mercury": swe.MERCURY, "Venus": swe.VENUS, "Mars": swe.MARS,
          "Jupiter": swe.JUPITER, "Saturn": swe.SATURN, "Uranus": swe.URANUS, "Neptune": swe.NEPTUNE}
PLACES = [("Hyderabad", 17.385, 78.4867), ("Kolkata", 22.5726, 88.3639), ("Delhi", 28.6139, 77.209),
          ("Ujjain", 23.1765, 75.7885), ("Chennai", 13.0827, 80.2707)]
# epochs: yearly with a drifting offset, 1900-2100 (UT); the engine supplies JDE for each
jds = [2415020.5 + k * 365.2422 + (k % 7) * 3.37 for k in range(0, 201)]
js = "const E=require('./lib/jyotish-ephem.js');console.log(JSON.stringify(%s.map(j=>E.jde(j))))" % json.dumps(jds)
jdes = json.loads(subprocess.check_output(["node", "-e", js]))
swe.set_sid_mode(swe.SIDM_LAHIRI, 0, 0)
rows = []
for jd, J in zip(jds, jdes):
    r = {"jd": jd, "jde": J}
    for name, b in BODIES.items():
        x, _ = swe.calc(J, b, FL)
        s, _ = swe.calc(J, b, FL | swe.FLG_SIDEREAL)
        r[name] = [round(x[0], 7), round(x[1], 7), round(s[0], 7)]
    mn, _ = swe.calc(J, swe.MEAN_NODE, FL)
    tn, _ = swe.calc(J, swe.TRUE_NODE, FL)
    r["meanNode"] = round(mn[0], 7); r["trueNode"] = round(tn[0], 7)
    nut, _ = swe.calc(J, swe.ECL_NUT, 0)
    r["eps"] = round(nut[0], 8); r["dpsi"] = round(nut[2], 8)
    rows.append(r)
rise = []
for name, lat, lon in PLACES:
    for k in range(0, 24):
        jd0 = 2451544.5 + k * 152.3 - lon / 360.0       # near local midnight, 2000-2010
        res, t = swe.rise_trans(jd0, swe.SUN, swe.CALC_RISE, (lon, lat, 0), 1013.25, 15, swe.FLG_MOSEPH)
        res2, t2 = swe.rise_trans(jd0, swe.SUN, swe.CALC_SET, (lon, lat, 0), 1013.25, 15, swe.FLG_MOSEPH)
        res3, t3 = swe.rise_trans(jd0, swe.MOON, swe.CALC_RISE, (lon, lat, 0), 1013.25, 15, swe.FLG_MOSEPH)
        rise.append({"place": name, "lat": lat, "lon": lon, "jd0": jd0, "sunrise": t[0], "sunset": t2[0], "moonrise": t3[0]})
asc = []
for k in range(0, 120):
    jd = 2451545.0 + k * 97.37 + 0.123
    name, lat, lon = PLACES[k % len(PLACES)]
    cusps, ascmc = swe.houses_ex(jd, lat, lon, b"W", swe.FLG_SIDEREAL | swe.FLG_MOSEPH)
    asc.append({"jd": jd, "lat": lat, "lon": lon, "ascSid": ascmc[0]})
out = {"_source": "pyswisseph %s, Moshier mode, SIDM_LAHIRI; generated by tools/oracle_sweph.py" % swe.version,
       "positions": rows, "rise": rise, "asc": asc}
json.dump(out, open("tests/vectors/oracle.json", "w"), separators=(",", ":"))
print("rows", len(rows), "rise", len(rise), "asc", len(asc))
