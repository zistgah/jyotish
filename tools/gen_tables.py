"""Generate lib/data/jyotish-series.js from pymeeus, never by hand.

Planetary series: VSOP87D (Bretagnon and Francou 1988) as carried by pymeeus.
Lunar series: Meeus (1998) Tables 47.A and 47.B, from ELP-2000/82 (Chapront).
Nutation: Meeus Table 22.A (IAU 1980). Terms below the amplitude floor are dropped,
and the error that costs is measured here against the full series, not assumed.
Usage: python3 tools/gen_tables.py [--floor N] [--check]
"""
import json, math, sys, importlib
import pymeeus
FLOOR = 30.0          # amplitude floor, 1e-8 rad (L, B) or 1e-8 AU (R)
if "--floor" in sys.argv:
    FLOOR = float(sys.argv[sys.argv.index("--floor") + 1])
BODIES = ["Mercury", "Venus", "Earth", "Mars", "Jupiter", "Saturn", "Uranus", "Neptune"]

def evaluate(levels, tau):
    total = 0.0
    for i, terms in enumerate(levels):
        s = sum(a * math.cos(b + c * tau) for a, b, c in terms)
        total += s * tau ** i
    return total / 1e8

def trim(levels, floor):
    # a level-i term contributes a * tau**i; |tau| <= 0.25 over 1750-2250
    return [[t for t in terms if abs(t[0]) * (0.25 ** i) >= floor or (i == 0 and t[2] == 0.0)]
            for i, terms in enumerate(levels)]

report, data = {}, {}
for name in BODIES:
    mod = importlib.import_module("pymeeus." + name)
    full = {k: getattr(mod, "VSOP87_" + k) for k in ("L", "B", "R")}
    cut = {k: trim(v, FLOOR) for k, v in full.items()}
    worst = {"L": 0.0, "B": 0.0, "R": 0.0}
    for year in range(1800, 2201, 4):
        tau = (year - 2000) / 1000.0
        for k in ("L", "B", "R"):
            worst[k] = max(worst[k], abs(evaluate(full[k], tau) - evaluate(cut[k], tau)))
    report[name] = {"terms_full": sum(len(t) for v in full.values() for t in v),
                    "terms_kept": sum(len(t) for v in cut.values() for t in v),
                    "max_err_L_arcsec": round(math.degrees(worst["L"]) * 3600, 4),
                    "max_err_B_arcsec": round(math.degrees(worst["B"]) * 3600, 4),
                    "max_err_R_au": float("%.3g" % worst["R"])}
    data[name] = {k: [[x for t in terms for x in t] for terms in v] for k, v in cut.items()}

if "--check" in sys.argv:
    print(json.dumps(report)); sys.exit(0)
moon = importlib.import_module("pymeeus.Moon")
coord = importlib.import_module("pymeeus.Coordinates")
out = {
    "meta": {"generator": "tools/gen_tables.py", "pymeeus": getattr(pymeeus, "__version__", "unknown"),
             "floor_1e8": FLOOR, "vsop": "VSOP87D via pymeeus (Bretagnon and Francou 1988)",
             "moon": "Meeus 1998 Tables 47.A/47.B from ELP-2000/82 via pymeeus",
             "nutation": "Meeus 1998 Table 22.A (IAU 1980) via pymeeus", "truncation": report},
    "vsop": data,
    "moonLR": moon.PERIODIC_TERMS_LR_TABLE, "moonB": moon.PERIODIC_TERMS_B_TABLE,
    "nutArg": coord.NUTATION_ARG_TABLE, "nutSin": coord.NUTATION_SINE_COEF_TABLE,
    "nutCos": coord.NUTATION_COSINE_COEF_TABLE,
}
js = ("/*! jyotish-series.js, GENERATED by tools/gen_tables.py. Do not edit by hand.\n"
      " * SPDX-License-Identifier: GPL-3.0-or-later. Coefficients are scientific data from\n"
      " * VSOP87D, ELP-2000/82 via Meeus Table 47, and IAU 1980 nutation, extracted from\n"
      " * pymeeus (LGPL-3.0). See THIRD_PARTY.md. */\n"
      "(function(r,f){if(typeof module==='object'&&module.exports)module.exports=f();"
      "else r.JyotishSeries=f();})(typeof self!=='undefined'?self:this,function(){return "
      + json.dumps(out, separators=(",", ":")) + ";});\n")
open("lib/data/jyotish-series.js", "w").write(js)
print("wrote lib/data/jyotish-series.js", len(js), "bytes")
print(json.dumps(report))
